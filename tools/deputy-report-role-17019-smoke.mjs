#!/usr/bin/env node
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const read = name => fs.readFileSync(name, 'utf8');
const auth=read('app-admin-unlock.js');
const menu=read('app-menu.js');
const renderer=read('app-menu-admin-renderer.js');
const entry=read('app-menu-shift-report.js');
const report=read('rak-shift-report.js');
const config=read('supabase-config.js');
const index=read('index.html');
const sw=read('sw.js');
assert(auth.includes('// RAK_REPORT_ONLY_DEPUTY_17019'), 'role gate marker');
const start=auth.indexOf('function rakAdminCanOpenShiftReport()');
const end=auth.indexOf('function rakAdminCanManageAdmins()',start);
assert(start>=0&&end>start,'role gate function bounds');
const scope={app:{adminAuthVersion:2,adminUnlocked:true,adminAccountId:'1234',adminRole:'deputy'},rakAdminGetActiveAccountId:()=>'1234'};
vm.createContext(scope);
vm.runInContext(auth.slice(start,end),scope);
for(const [role,reportAllowed,adminAllowed] of [['owner',true,true],['admin',true,true],['deputy',true,false],['guest',false,false]]){
  scope.app.adminRole=role;
  assert.equal(scope.rakAdminCanOpenShiftReport(),reportAllowed,role+' report');
  assert.equal(scope.rakAdminCanOpenAdmin(),adminAllowed,role+' admin');
  assert.equal(scope.rakAdminIsDeputy(),role==='deputy',role+' deputy flag');
}
scope.app.adminRole='deputy';scope.app.adminUnlocked=false;
assert.equal(scope.rakAdminCanOpenShiftReport(),false,'locked denied');
scope.app.adminUnlocked=true;scope.app.adminAccountId='other';
assert.equal(scope.rakAdminCanOpenShiftReport(),false,'account mismatch denied');
scope.app.adminAccountId='1234';scope.app.adminAuthVersion=0;
assert.equal(scope.rakAdminCanOpenShiftReport(),false,'unauthenticated denied');
assert(auth.includes("['admin', 'deputy'].includes(entry.role)"),'existing deputies kept in owner save');
assert(auth.includes("role: String(row.querySelector('[data-admin-account-role]')?.value || 'admin')"),'role captured from UI');
assert(auth.includes('data-admin-account-role aria-label='),'role select rendered');
assert(auth.includes('role: String(entry.role || \'admin\')'),'role preserved when disabling');
assert(auth.includes("app.adminRole = '';"),'lock clears role');
assert(menu.includes('// RAK_REPORT_ONLY_DEPUTY_17019'),'deputy-only navigation marker');
assert(menu.includes("rakAdminIsDeputy() ? '' :"),'no admin/vacation quick links for deputy');
assert(menu.includes('data-rak-shift-report-entry="1"'),'deputy report entry remains');
assert(menu.includes("rakAdminCanOpenAdmin()))"),'admin route remains role-gated');
assert(renderer.includes('// RAK_REPORT_ONLY_DEPUTY_17019')&&renderer.includes('rakAdminCanOpenAdmin()'),'direct renderer guard');
assert(entry.includes('window.rakAdminCanOpenShiftReport()')&&!entry.includes('window.rakAdminCanOpenAdmin()'),'entry only accepts report role');
assert(report.includes("function canUseShiftReport(){return typeof rakAdminCanOpenShiftReport==='function'&&rakAdminCanOpenShiftReport();}"),'report open guard');
assert(report.includes('if(!canUseShiftReport()){e.preventDefault();return;}'),'report actions recheck auth');
assert((report.match(/rakAdminIsDeputy/g)||[]).length>=2,'report close and clear go back to menu');
assert(config.includes('https://cgshssdjgzzuprlwnabl.supabase.co')&&!config.includes('bkqamcbkiwumsvelahxr'),'test DB isolation');
assert(config.includes('window.RAK_RELEASE_VERSION = "1.7.19";'),'display');
assert(config.includes('window.RAK_PWA_BUILD = "v1.7.19-deputy1";'),'build');
assert(index.includes("var build='v1.7.19-deputy1';"),'index');
assert(sw.includes("const CACHE_VERSION = 'v1.7.19';"),'cache');
assert.equal(JSON.parse(read('package.json')).version,'1.7.0','technical version');
console.log('[deputy-report-role-17019-smoke] OK deputy report-only, owner/admin unchanged, auth mismatch/lock denied, account role CRUD, private menu, direct renderer guard, report buttons, test DB and release');